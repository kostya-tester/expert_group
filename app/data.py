def apply_exclusion_criteria(params: dict) -> tuple[list, dict]:
    """
    Применяет шесть исключающих критериев.
    params:
        production   — "серийное" | "опытное"
        has_filler   — bool
        thickness    — float (мм)
        has_radius   — bool
        area         — float (м²)
        min_defect   — float (мм)
    Возвращает (доступные_методы, лог_исключений).
    """
    all_methods = list(METHOD_SCORES.keys())
    excluded = {m: [] for m in all_methods}

    if params["production"] == "серийное":
        excluded["КТ"].append("Критерий 1: серийное производство")

    if params["has_filler"]:
        excluded["УЗК"].append("Критерий 2: наличие заполнителя")
        excluded["РК"].append("Критерий 2: наличие заполнителя")

    if params["thickness"] > 3:
        excluded["Импеданс"].append("Критерий 3: толщина > 3 мм")
        excluded["Ширография"].append("Критерий 3: толщина > 3 мм")

    if params["has_radius"]:
        excluded["УЗК"].append("Критерий 4: радиусные зоны")
        excluded["Импеданс"].append("Критерий 4: радиусные зоны")

    if params["area"] < 1.0:
        excluded["Ширография"].append("Критерий 5: площадь < 1 м²")
        excluded["Термография"].append("Критерий 5: площадь < 1 м²")
        excluded["РК"].append("Критерий 5: площадь < 1 м²")

    if params["min_defect"] < 5:
        excluded["Импеданс"].append("Критерий 6: требуемый дефект < 5 мм")
        excluded["Ширография"].append("Критерий 6: требуемый дефект < 5 мм")
        excluded["Термография"].append("Критерий 6: требуемый дефект < 5 мм")

    available = [m for m in all_methods if not excluded[m]]
    # УЗК ФР не исключается самостоятельно — он идёт вместе с УЗК
    # Но если УЗК исключён, УЗК ФР остаётся (он не зависит от тех же ограничений)
    return available, excluded


def score_methods(available: list, weights: dict = None) -> list:
    """
    Рассчитывает взвешенную сумму для каждого доступного метода.
    Возвращает список [(метод, балл), ...] отсортированный по убыванию.
    """
    if weights is None:
        weights = DEFAULT_WEIGHTS
    w = [weights[f"w{i}"] for i in range(1, 6)]
    w_sum = sum(w)
    results = []
    for m in available:
        s = METHOD_SCORES[m]
        score = sum([s[f"c{i+1}"] * w[i] for i in range(5)]) / w_sum
        results.append((m, round(score, 2)))
    results.sort(key=lambda x: (-x[1], -METHOD_SCORES[x[0]]["c5"]))
    return results


def get_auxiliary(main_method: str, construction: str, production: str) -> tuple:
    key = (main_method, construction, production)
    return AUX_METHOD_MATRIX.get(key, (None, "Вспомогательный метод не определён для данной комбинации"))


def get_defects_for_methods(methods: list) -> list:
    """Возвращает список дефектов, выявляемых хотя бы одним из методов."""
    result = []
    for d in ALL_DEFECTS:
        for m in methods:
            if any(m in det for det in d["methods_detecting"]):
                result.append(d)
                break
    return result
